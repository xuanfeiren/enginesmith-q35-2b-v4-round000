// "prompt": [ids] read without building a JSON value per id (a 4096-id prompt took ~0.35 ms through json::parse).
// Returns the line with the array emptied and sets ok; any unexpected character in the array: ok = false (the caller
// then parses the line as it is).
static std::string fast_prompt(const std::string& line, std::vector<int>& out, bool& ok) {
  ok = false;
  size_t k = line.find("\"prompt\"");
  if (k == std::string::npos || line.find("\"prompt\"", k + 1) != std::string::npos) return std::string();
  size_t i = k + 8;
  while (i < line.size() && (line[i] == ' ' || line[i] == '\t')) i++;
  if (i >= line.size() || line[i] != ':') return std::string();
  i++;
  while (i < line.size() && (line[i] == ' ' || line[i] == '\t')) i++;
  if (i >= line.size() || line[i] != '[') return std::string();
  size_t open = i++;
  out.clear();
  out.reserve(line.size() / 4);
  bool need = false;   // a number must follow (after a comma)
  while (i < line.size()) {
    char c = line[i];
    if (c == ' ' || c == '\t' || c == '\r' || c == '\n') { i++; continue; }
    if (c == ']') { if (need) return std::string(); break; }
    if (c == ',') { if (out.empty() || need) return std::string(); need = true; i++; continue; }
    if (!out.empty() && !need) return std::string();
    bool neg = false;
    if (c == '-') { neg = true; i++; }
    if (i >= line.size() || line[i] < '0' || line[i] > '9') return std::string();
    long long v = 0;
    int nd = 0;
    while (i < line.size() && line[i] >= '0' && line[i] <= '9') { v = v * 10 + (line[i] - '0'); i++; if (++nd > 12) return std::string(); }
    if (i < line.size() && (line[i] == '.' || line[i] == 'e' || line[i] == 'E')) return std::string();
    out.push_back((int)(neg ? -v : v));
    need = false;
  }
  if (i >= line.size()) return std::string();
  ok = true;
  return line.substr(0, open + 1) + line.substr(i);
}

static void reply(const std::string& s) { fwrite(s.data(), 1, s.size(), g_out); fputc('\n', g_out); fflush(g_out); }

int main(int argc, char** argv) {
  std::string model;
  for (int i = 1; i < argc; i++) if (!strcmp(argv[i], "--model") && i + 1 < argc) model = argv[++i];
  if (model.empty()) { fprintf(stderr, "usage: %s --model MODEL_DIR\n", argv[0]); return 2; }
  g_verbose = getenv("ENGINE_VERBOSE") != nullptr;
  // protocol replies go to a private copy of stdout; fd 1 becomes stderr (libnrt may print)
  int fd = dup(1);
  g_out = fdopen(fd, "w");
  dup2(2, 1);

  Engine E;
  try {
    auto t0 = clk::now();
    CK(nrt_init(NRT_FRAMEWORK_TYPE_NO_FW, "", ""));
    E.load_neffs();
    logf("NEFFs loaded in %.0f ms", ms_since(t0));
    E.load_weights(model);
    E.build_sets();
    logf("ready in %.0f ms", ms_since(t0));
  } catch (std::exception& e) {
    logf("fatal: %s", e.what());
    return 1;
  }

  // stdin is read non-blocking; after the last input the loop spins for 10 s before blocking in poll()
  // (a process asleep in read() answered the next request measurably later)
  fcntl(0, F_SETFL, fcntl(0, F_GETFL) | O_NONBLOCK);
  std::string inbuf, line;
  bool eof = false;
  auto last_input = clk::now();
  auto next_line = [&](std::string& out) -> bool {
    while (true) {
      size_t nl = inbuf.find('\n');
      if (nl != std::string::npos) { out = inbuf.substr(0, nl + 1); inbuf.erase(0, nl + 1); return true; }
      if (eof) { if (inbuf.empty()) return false; out.swap(inbuf); inbuf.clear(); return true; }
      char buf[1 << 16];
      ssize_t r = ::read(0, buf, sizeof buf);
      if (r > 0) { inbuf.append(buf, (size_t)r); last_input = clk::now(); continue; }
      if (r == 0) { eof = true; continue; }
      if (errno != EAGAIN && errno != EWOULDBLOCK && errno != EINTR) { eof = true; continue; }
      if (ms_since(last_input) > 10000.0) { struct pollfd pf = {0, POLLIN, 0}; poll(&pf, 1, -1); }
    }
  };
  while (true) {
    if (!next_line(line)) break;
    if (line.find_first_not_of(" \r\n\t") == std::string::npos) continue;
    json::Value id;
    try {
      // the prompt (up to 8192 ids) is read by a fast integer scan; the rest of the request by the JSON reader
      std::vector<int> fprompt;
      bool fast = false;
      std::string rest = fast_prompt(line, fprompt, fast);
      json::Value req = json::parse(fast ? rest : line);
      id = req["id"];
      std::string op = req["op"].str;
      if (op == "hello") {
        reply("{\"id\":" + json::dump(id) + ",\"ok\":true,\"protocol\":1}");
      } else if (op == "generate") {
        std::vector<int> prompt;
        if (fast) prompt.swap(fprompt);
        else for (auto& v : req["prompt"].arr) prompt.push_back((int)v.num);
        int mt = (int)req["max_tokens"].num;
        bool reset = req["reset"].b;
        auto t0 = clk::now();
        auto toks = E.generate(prompt, mt, reset);
        if (g_verbose) logf("generate prompt=%zu max=%d reset=%d: %.1f ms", prompt.size(), mt, (int)reset, ms_since(t0));
        std::string s = "{\"id\":" + json::dump(id) + ",\"ok\":true,\"tokens\":[";
        for (size_t i = 0; i < toks.size(); i++) { if (i) s += ","; s += std::to_string(toks[i]); }
        s += "]}";
        reply(s);
      } else {
        throw std::runtime_error("unknown op " + op);
      }
    } catch (std::exception& e) {
      logf("error: %s", e.what());
      reply("{\"id\":" + json::dump(id) + ",\"ok\":false,\"error\":" + json::quote(e.what()) + "}");
    }
  }
  nrt_close();
  return 0;
}
