// host re-layouts (values unchanged)
static void parallel_for(int n, const std::function<void(int)>& f) {
  int nt = std::min<int>(n, std::max(1u, std::min(32u, std::thread::hardware_concurrency())));
  std::vector<std::thread> th;
  for (int w = 0; w < nt; w++) th.emplace_back([&, w] { for (int i = w; i < n; i += nt) f(i); });
  for (auto& x : th) x.join();
}

// W [N, K] bf16 row-major -> [128 p][NT][KT][128 j], element = W[nt*128 + j][kt*128 + p]
static std::vector<uint16_t> relayout_fm(const uint16_t* W, int N, int K) {
  int NT = N / P, KTl = K / P;
  std::vector<uint16_t> out((size_t)N * K);
  parallel_for(P, [&](int p) {
    uint16_t* o = out.data() + (size_t)p * NT * KTl * P;
    for (int nt = 0; nt < NT; nt++)
      for (int kt = 0; kt < KTl; kt++) {
        const uint16_t* src = W + (size_t)(nt * P) * K + kt * P + p;
        uint16_t* dst = o + ((size_t)nt * KTl + kt) * P;
        for (int j = 0; j < P; j++) dst[j] = src[(size_t)j * K];
      }
  });
  return out;
}

// per-core N-split: core c gets the rows listed in rows[c] (each a multiple of 128 long) of W [N, K];
// result [2][128 p][NTc][KT][128 j] (core-major), each core's block as relayout_fm of its row subset
static std::vector<uint16_t> relayout_split(const uint16_t* W, int K, const std::vector<std::vector<int>>& rows) {
  size_t nc = rows[0].size();
  std::vector<uint16_t> out(2 * nc * K);
  for (int c = 0; c < 2; c++) {
    std::vector<uint16_t> sub(nc * K);
    for (size_t r = 0; r < nc; r++) memcpy(sub.data() + r * K, W + (size_t)rows[c][r] * K, (size_t)K * 2);
    auto r = relayout_fm(sub.data(), (int)nc, K);
    memcpy(out.data() + c * nc * K, r.data(), r.size() * 2);
  }
  return out;
}
// rows [a_c + i] for blocks given as (start for core 0, start for core 1, length)
static std::vector<std::vector<int>> rowsets(std::initializer_list<std::array<int, 3>> blocks) {
  std::vector<std::vector<int>> r(2);
  for (auto& b : blocks) for (int c = 0; c < 2; c++) for (int i = 0; i < b[2]; i++) r[c].push_back(b[c] + i);
  return r;
}

// vector [nt*128] -> [128 p][nt]
template <class T> static std::vector<T> relayout_vec(const T* w, int n) {
  int nt = n / P; std::vector<T> o(n);
  for (int p = 0; p < P; p++) for (int k = 0; k < nt; k++) o[p * nt + k] = w[k * P + p];
  return o;
}

static uint16_t f2bf(float f) { uint32_t u; memcpy(&u, &f, 4); u += 0x7fff + ((u >> 16) & 1); return (uint16_t)(u >> 16); }

// ------------------------------------------------------------------------------------------------
struct Neff {
  nrt_model_t* m = nullptr;
  std::vector<std::string> ins, outs;
};

struct Engine {
  int vnc = 0;
  std::map<std::string, Neff> neff;
  std::vector<nrt_tensor_t*> owned;

  nrt_tensor_t* alloc(size_t bytes, const char* name) {
    nrt_tensor_t* t; CK(nrt_tensor_allocate(NRT_TENSOR_PLACEMENT_DEVICE, vnc, bytes, name, &t));
    owned.push_back(t); return t;
  }
  nrt_tensor_t* upload(const void* data, size_t bytes, const char* name) {
    nrt_tensor_t* t = alloc(bytes, name);
    CK(nrt_tensor_write(t, data, 0, bytes));
    return t;
  }
  // per-layer tensors live in stacked device tensors ("l_" + key: the 18 DeltaNet layers, "f_" + key: the 6
  // full-attention layers), so the fused decode step takes one tensor per kind; per-layer NEFFs get slices.
  std::map<std::string, nrt_tensor_t*> stacked;
  std::map<std::string, size_t> stacked_bytes;
  nrt_tensor_t* slot(int l, const std::string& key, size_t bytes) {
    bool full = (l % 4) == 3;
    std::string sk = (full ? "f_" : "l_") + key;
    int idx = full ? l / 4 : l - l / 4, count = full ? NLAYER / 4 : NLAYER - NLAYER / 4;
    auto it = stacked.find(sk);
    if (it == stacked.end()) { it = stacked.emplace(sk, alloc(bytes * count, sk.c_str())).first; stacked_bytes[sk] = bytes * count; }
    nrt_tensor_t* sl;
    CK(nrt_tensor_allocate_slice(it->second, bytes * idx, bytes, key.c_str(), &sl));
    return sl;
  }
  nrt_tensor_t* put(int l, const std::string& key, const void* data, size_t bytes) {
    nrt_tensor_t* t = slot(l, key, bytes);
    CK(nrt_tensor_write(t, data, 0, bytes));
    return t;
  }
  void zero(nrt_tensor_t* t, size_t bytes) {
    static std::vector<uint8_t> z;
    if (z.size() < bytes) z.assign(bytes, 0);
    CK(nrt_tensor_write(t, z.data(), 0, bytes));
  }

  // device tensors
  nrt_tensor_t *toks, *pos, *posf, *tokout, *advout, *zout, *emb, *wlm, *vofs, *lnf, *cosT, *sinT, *rot, *dnc;
  std::map<int, nrt_tensor_t*> xbuf[2];   // per T: ping-pong hidden buffers
  struct Layer {
    bool full;
    std::map<std::string, nrt_tensor_t*> w;
    nrt_tensor_t *st0 = nullptr, *st1 = nullptr;  // lin: conv, rec ; full: kc, vc
    size_t st0b = 0, st1b = 0;
  } layer[NLAYER];

  // tensor sets: key "kernel|layer"
  std::map<std::string, std::pair<nrt_tensor_set_t*, nrt_tensor_set_t*>> sets;

  // NEFFs are loaded by several threads at once (nrt_load of 64 NEFFs one by one took ~45 s)
  void load_neffs() {
    std::vector<Neff> loaded(engine_neff_count);
    std::atomic<int> next{0};
    std::atomic<bool> failed{false};
    std::string err;
    std::mutex mu;
    auto work = [&]() {
      for (int i; (i = next++) < engine_neff_count && !failed;) {
        const NeffBlob& b = engine_neffs[i];
        Neff& n = loaded[i];
        auto t0 = clk::now();
        NRT_STATUS st = nrt_load(b.data, (size_t)(b.end - b.data), vnc, 1, &n.m);
        nrt_tensor_info_array_t* info = nullptr;
        if (st == NRT_SUCCESS) st = nrt_get_model_tensor_info(n.m, &info);
        if (st != NRT_SUCCESS) {
          std::lock_guard<std::mutex> g(mu);
          failed = true; err = std::string("nrt_load failed for ") + b.name + " (status " + std::to_string((int)st) + ")";
          return;
        }
        for (uint64_t k = 0; k < info->tensor_count; k++) {
          auto& ti = info->tensor_array[k];
          (ti.usage == NRT_TENSOR_USAGE_INPUT ? n.ins : n.outs).push_back(ti.name);
        }
        if (g_verbose) logf("loaded %s (%.1f ms) inputs=%zu outputs=%zu", b.name, ms_since(t0), n.ins.size(), n.outs.size());
      }
    };
    std::vector<std::thread> th;
    for (int t = 0; t < 8; t++) th.emplace_back(work);
    for (auto& t : th) t.join();
    if (failed) throw std::runtime_error(err);
    for (int i = 0; i < engine_neff_count; i++) neff[engine_neffs[i].name] = loaded[i];
  }

  void load_weights(const std::string& dir) {
    SafeTensors st; st.open_dir(dir);
    const std::string pre = "model.language_model.";
    auto bf = [&](const std::string& n, std::vector<int64_t> s) { return (const uint16_t*)st.get(pre + n, "BF16", s).data; };
    auto f32 = [&](const std::string& n, std::vector<int64_t> s) { return (const float*)st.get(pre + n, "F32", s).data; };
    auto t0 = clk::now();
    const uint16_t* E = bf("embed_tokens.weight", {VOCAB, D});
    emb = upload(E, (size_t)VOCAB * D * 2, "emb");
    { auto r = relayout_split(E, D, rowsets({{0, VOCAB / 2, VOCAB / 2}})); wlm = upload(r.data(), r.size() * 2, "wlm"); }
    { std::vector<float> v(2 * P); for (int c = 0; c < 2; c++) for (int p = 0; p < P; p++) v[c * P + p] = -(float)(c * (VOCAB / 2));
      vofs = upload(v.data(), v.size() * 4, "vofs"); }
    { auto r = relayout_vec(bf("norm.weight", {D}), D); lnf = upload(r.data(), r.size() * 2, "lnf"); }
    for (int l = 0; l < NLAYER; l++) {
      Layer& L = layer[l];
      std::string lp = "layers." + std::to_string(l) + ".";
      L.full = (l % 4) == 3;
      auto split = [&](const char* key, const std::string& n, int N, int K, std::initializer_list<std::array<int, 3>> blocks) {
        auto r = relayout_split(bf(lp + n, {N, K}), K, rowsets(blocks)); L.w[key] = put(l, key, r.data(), r.size() * 2);
      };
      auto vec = [&](const char* key, const std::string& n, int len) {
        auto r = relayout_vec(bf(lp + n, {len}), len); L.w[key] = put(l, key, r.data(), r.size() * 2);
      };
      vec("ln1", "input_layernorm.weight", D);
      vec("ln2", "post_attention_layernorm.weight", D);
      split("wg", "mlp.gate_proj.weight", DFF, D, {{0, DFF / 2, DFF / 2}});
      split("wu", "mlp.up_proj.weight", DFF, D, {{0, DFF / 2, DFF / 2}});
      split("wd", "mlp.down_proj.weight", D, DFF, {{0, D / 2, D / 2}});
      if (!L.full) {
        // core c: heads 8c..8c+7 -> q rows 1024c.., k rows 2048 + 1024c.., v rows 4096 + 1024c..
        split("wqkv", "linear_attn.in_proj_qkv.weight", NQKV, D, {{0, 1024, 1024}, {2048, 3072, 1024}, {4096, 5120, 1024}});
        split("wz", "linear_attn.in_proj_z.weight", D, D, {{0, 1024, 1024}});
        split("wout", "linear_attn.out_proj.weight", D, D, {{0, 1024, 1024}});
        {  // wab: (c, p, kt, j) = [b; a][8c + j mod 8, kt*128 + p]
          const uint16_t* B = bf(lp + "linear_attn.in_proj_b.weight", {16, D});
          const uint16_t* A = bf(lp + "linear_attn.in_proj_a.weight", {16, D});
          std::vector<uint16_t> r((size_t)2 * P * KT * 16);
          for (int c = 0; c < 2; c++) for (int p = 0; p < P; p++) for (int kt = 0; kt < KT; kt++) for (int j = 0; j < 16; j++)
            r[(((size_t)c * P + p) * KT + kt) * 16 + j] =
                (j < 8 ? B[(size_t)(8 * c + j) * D + kt * P + p] : A[(size_t)(8 * c + j - 8) * D + kt * P + p]);
          L.w["wab"] = put(l, "wab", r.data(), r.size() * 2);
        }
        {  // conv weight [6144, 1, 4] -> (c, p, local tile, j); local tiles = q, k, v tiles of the core's heads
          const uint16_t* C = bf(lp + "linear_attn.conv1d.weight", {NQKV, 1, 4});
          std::vector<uint16_t> r((size_t)2 * P * 24 * 4);
          for (int c = 0; c < 2; c++) for (int p = 0; p < P; p++) for (int lt = 0; lt < 24; lt++) {
            int gt = (lt / 8) * 16 + 8 * c + lt % 8;
            for (int j = 0; j < 4; j++) r[(((size_t)c * P + p) * 24 + lt) * 4 + j] = C[(size_t)(gt * P + p) * 4 + j];
          }
          L.w["convw"] = put(l, "convw", r.data(), r.size() * 2);
          // diag(w) stationaries for the prefill conv on the TensorE: (c, p, lt*4 + j, m) = (p == m) * w
          std::vector<uint16_t> dg((size_t)2 * P * 96 * P, 0);
          for (int c = 0; c < 2; c++) for (int p = 0; p < P; p++) for (int q = 0; q < 96; q++)
            dg[(((size_t)c * P + p) * 96 + q) * P + p] = r[(((size_t)c * P + p) * 24 + q / 4) * 4 + q % 4];
          L.w["cdiag"] = put(l, "cdiag", dg.data(), dg.size() * 2);
        }
        {  // A_log (fp32) and dt_bias (bf16) of the core's heads, rows replicated: [2, P, 8]
          const float* al = f32(lp + "linear_attn.A_log", {16});
          const uint16_t* dtb = bf(lp + "linear_attn.dt_bias", {16});
          std::vector<float> a(2 * P * 8); std::vector<uint16_t> d(2 * P * 8);
          for (int c = 0; c < 2; c++) for (int p = 0; p < P; p++) for (int j = 0; j < 8; j++) {
            a[(c * P + p) * 8 + j] = al[8 * c + j]; d[(c * P + p) * 8 + j] = dtb[8 * c + j];
          }
          L.w["alog"] = put(l, "alog", a.data(), a.size() * 4);
          L.w["dtb"] = put(l, "dtb", d.data(), d.size() * 2);
        }
        L.w["normw"] = put(l, "normw", f32(lp + "linear_attn.norm.weight", {128}), 512);
        L.st0b = (size_t)2 * P * 24 * 3 * 2;   L.st0 = slot(l, "convst", L.st0b);
        L.st1b = (size_t)2 * P * 8 * 128 * 4;  L.st1 = slot(l, "recst", L.st1b);
      } else {
        // core c: query heads 4c..4c+3 (q and gate rows interleaved per head), KV head c
        split("wq", "self_attn.q_proj.weight", 4096, D, {{0, 2048, 2048}});
        split("wk", "self_attn.k_proj.weight", 512, D, {{0, 256, 256}});
        split("wv", "self_attn.v_proj.weight", 512, D, {{0, 256, 256}});
        split("wo", "self_attn.o_proj.weight", D, D, {{0, 1024, 1024}});
        vec("qnw", "self_attn.q_norm.weight", 256);
        vec("knw", "self_attn.k_norm.weight", 256);
        L.st0b = (size_t)2 * 2 * P * MAXPOS * 2; L.st0 = slot(l, "kc", L.st0b);
        L.st1b = (size_t)2 * MAXPOS * 256 * 2;   L.st1 = slot(l, "vc", L.st1b);
      }
    }
    // RoPE tables (position constants, as transformers computes them: fp32, then bf16), feature-major [64, MAXPOS]
    {
      float inv[32];
      for (int i = 0; i < 32; i++) inv[i] = 1.0f / powf(10000000.0f, (float)(2 * i) / 64.0f);
      std::vector<uint16_t> c((size_t)64 * MAXPOS), s((size_t)64 * MAXPOS);
      for (int d = 0; d < 64; d++) for (int p = 0; p < MAXPOS; p++) {
        float f = inv[d % 32] * (float)p;
        c[(size_t)d * MAXPOS + p] = f2bf(cosf(f)); s[(size_t)d * MAXPOS + p] = f2bf(sinf(f));
      }
      cosT = upload(c.data(), c.size() * 2, "cos"); sinT = upload(s.data(), s.size() * 2, "sin");
      std::vector<uint16_t> r((size_t)P * P, 0);
      const uint16_t one = 0x3f80, mone = 0xbf80;
      for (int m = 0; m < 32; m++) r[(size_t)(m + 32) * P + m] = mone;      // out[m] = -x[m+32]
      for (int m = 32; m < 64; m++) r[(size_t)(m - 32) * P + m] = one;      // out[m] = x[m-32]
      rot = upload(r.data(), r.size() * 2, "rot");
    }
    {  // constant masks of the chunked delta rule, [128 p][13][128 j] fp32 (p = partition index)
      const int NM = 13, b = 8;
      std::vector<float> m((size_t)P * NM * P, 0.0f);
      auto at = [&](int k, int i, int j) -> float& { return m[((size_t)i * NM + k) * P + j]; };
      for (int i = 0; i < P; i++) for (int j = 0; j < P; j++) {
        at(0, i, j) = i <= j ? 1.0f : 0.0f;              // Ut[t, i]: t <= i (cumsum over tokens)
        at(1, i, j) = j >= i ? -1.0e30f : 0.0f;          // [i, j]: keep j < i
        at(2, i, j) = i > j ? -1.0e30f : 0.0f;           // [j, i]: keep j <= i
        at(3, i, j) = (i / b == j / b) && j < i;         // strictly lower part of the 8-blocks
        at(4, i, j) = (i / b == j / b) && i < j;         // (transpose)
        for (int lv = 0; lv < 4; lv++) {                 // lower off-diagonal block of each 2s pair, s = 8 .. 64
          int s = 8 << lv;
          at(5 + lv, i, j) = (i / (2 * s) == j / (2 * s)) && (i / s) % 2 == 1 && (j / s) % 2 == 0;
          at(9 + lv, i, j) = (i / (2 * s) == j / (2 * s)) && (j / s) % 2 == 1 && (i / s) % 2 == 0;   // transpose of 5 + lv
        }
      }
      dnc = upload(m.data(), m.size() * 4, "dnc");
    }
    for (const char* k : {"l_convst", "l_recst", "f_kc", "f_vc"}) zero(stacked.at(k), stacked_bytes.at(k));
    toks = alloc((MAXPOS + 128) * 4, "toks"); zero(toks, (MAXPOS + 128) * 4);
    pos = alloc(2 * 4, "pos"); posf = alloc(2 * P * 4, "posf"); tokout = alloc(4, "tokout"); advout = alloc(4, "advout"); zout = alloc(4, "zout");
    for (int t : {1, 128, 256, 512}) for (int i = 0; i < 2; i++) { xbuf[i][t] = alloc((size_t)P * KT * t * 2, "x"); zero(xbuf[i][t], (size_t)P * KT * t * 2); }
    logf("weights uploaded in %.0f ms", ms_since(t0));
    for (auto& m : st.maps) munmap(m.first, m.second);
  }

  std::pair<nrt_tensor_set_t*, nrt_tensor_set_t*> make_set(const std::string& kname, const std::map<std::string, nrt_tensor_t*>& in,
                                                          nrt_tensor_t* out) {
    Neff& n = neff.at(kname);
    nrt_tensor_set_t *si, *so;
    CK(nrt_allocate_tensor_set(&si)); CK(nrt_allocate_tensor_set(&so));
    for (auto& name : n.ins) {
      auto it = in.find(name);
      if (it == in.end()) throw std::runtime_error("kernel " + kname + ": no tensor bound for input " + name);
      CK(nrt_add_tensor_to_tensor_set(si, name.c_str(), it->second));
    }
    if (n.outs.size() != 1) throw std::runtime_error("kernel " + kname + " has unexpected outputs");
    CK(nrt_add_tensor_to_tensor_set(so, n.outs[0].c_str(), out));
    return {si, so};
  }

  // prefill chunk variant for t tokens at position p: 512-chunks (at multiples of 512) and the 256-chunk at 0 use the
  // exact bucket p + t ("t" variants, attention trimmed per sub-chunk); the others the smallest bucket >= p + t
  static std::string pchunk_name(int t, int p) {
    if (t == 512 || (t == 256 && p == 0)) return "pchunk" + std::to_string(t) + "_l" + std::to_string(p + t) + "t";
    for (int b : BUCKETS) if (p + t <= b) return "pchunk" + std::to_string(t) + "_l" + std::to_string(b);
    return "";
  }

  void build_sets() {
    for (int t : PCHUNK_TS) {
      std::vector<std::string> names;
      if (t == 512) for (int b = 512; b <= MAXPOS; b += 512) names.push_back("pchunk512_l" + std::to_string(b) + "t");
      else for (int b : BUCKETS) names.push_back("pchunk" + std::to_string(t) + "_l" + std::to_string(b));
      if (t == 256) names.push_back("pchunk256_l256t");
      for (auto& k : names) {
        std::map<std::string, nrt_tensor_t*> in = stacked;
        in["toks"] = toks; in["pos"] = pos; in["posf"] = posf; in["emb"] = emb; in["cos"] = cosT; in["sin"] = sinT;
        in["rot"] = rot; in["dnc"] = dnc;
        sets[k] = make_set(k, in, xbuf[0][t]);
        // the same chunk with the LM head fused in, for the last chunk of a prompt (built for the exact-bucket
        // variants: pchunk512_l*t, pchunk256_l256t)
        std::string kh = k + "h";
        // the TIGHT variants (names ending in "t") skip the last layer's output (only its K / V cache is written,
        // kernels/qwen35.py KVLAST): they must never be the last chunk of a prompt, so their fused-head twin must exist
        if (k.back() == 't' && !neff.count(kh)) throw std::runtime_error("missing fused-head variant " + kh);
        if (neff.count(kh)) {
          in["lnf"] = lnf; in["wlm"] = wlm; in["vofs"] = vofs;
          sets[kh] = make_set(kh, in, tokout);
        }
      }
      std::string h = "headna_t" + std::to_string(t);
      sets[h] = make_set(h, {{"x", xbuf[0][t]}, {"lnf", lnf}, {"wlm", wlm}, {"vofs", vofs},
                             {"toks", toks}, {"pos", pos}, {"posf", posf}}, tokout);
    }
    sets["zero_states"] = make_set("zero_states", {{"l_convst", stacked.at("l_convst")}, {"l_recst", stacked.at("l_recst")}}, zout);
    for (int b : STEP_BUCKETS) {
      std::map<std::string, nrt_tensor_t*> in = stacked;
      in["toks"] = toks; in["pos"] = pos; in["posf"] = posf; in["emb"] = emb; in["lnf"] = lnf; in["wlm"] = wlm;
      in["vofs"] = vofs; in["cos"] = cosT; in["sin"] = sinT; in["rot"] = rot;
      std::string k = "step_l" + std::to_string(b);
      sets[k] = make_set(k, in, tokout);
    }
    for (int t : TS) {
      std::string ts = std::to_string(t);
      sets["embed_t" + ts] = make_set("embed_t" + ts, {{"toks", toks}, {"pos", pos}, {"emb", emb}}, xbuf[0][t]);
      sets["head_t" + ts] = make_set("head_t" + ts, {{"x", xbuf[0][t]}, {"lnf", lnf}, {"wlm", wlm}, {"vofs", vofs},
                                                     {"toks", toks}, {"pos", pos}, {"posf", posf}}, tokout);
      sets["adv_t" + ts] = make_set("adv_t" + ts, {{"pos", pos}, {"posf", posf}}, advout);
      for (int l = 0; l < NLAYER; l++) {
        Layer& L = layer[l];
        std::map<std::string, nrt_tensor_t*> in = L.w;
        in["x"] = xbuf[l % 2][t];
        nrt_tensor_t* out = xbuf[(l + 1) % 2][t];
        if (!L.full) {
          in["convst"] = L.st0; in["recst"] = L.st1; in["dnc"] = dnc;
          sets["lin_t" + ts + "|" + std::to_string(l)] = make_set("lin_t" + ts, in, out);
        } else {
          in["kc"] = L.st0; in["vc"] = L.st1; in["pos"] = pos; in["posf"] = posf;
          in["cos"] = cosT; in["sin"] = sinT; in["rot"] = rot;
          for (int b : BUCKETS) {
            std::string k = "full_t" + ts + "_l" + std::to_string(b);
            sets[k + "|" + std::to_string(l)] = make_set(k, in, out);
          }
        }
      }
    }
  }

  // queued executions of the current request (nrta_execute_schedule, in order on queue 0)
  struct Call { nrt_model_t* m; nrt_tensor_set_t* in; nrt_tensor_set_t* out; };
  std::vector<Call> calls;
  std::map<std::string, Call> callmap;

  const Call& call(const std::string& kname, const std::string& setkey) {
    auto it = callmap.find(setkey);
    if (it == callmap.end()) {
      auto& s = sets.at(setkey);
      it = callmap.emplace(setkey, Call{neff.at(kname).m, s.first, s.second}).first;
    }
    return it->second;
  }

  // one fused prefill chunk of t (128, 256 or 512) tokens at position p (tokens in toks[p .. p+t-1]; hidden state -> xbuf[0][t])
  void add_pchunk(int t, int p) {
    std::string k = pchunk_name(t, p);
    if (k.empty() || !sets.count(k)) throw std::runtime_error("position beyond the compiled limit");
    calls.push_back(call(k, k));
  }

  // one fused decode step at position p (token in toks[p]; next token -> toks[p+1])
  void add_step(int p) {
    for (int b : STEP_BUCKETS) if (p + 1 <= b) { std::string k = "step_l" + std::to_string(b); calls.push_back(call(k, k)); return; }
    throw std::runtime_error("position beyond the compiled limit");
  }

  // one chunk of T tokens at position p (tokens already in toks[p .. p+T-1]); with head: token -> toks[p+T]
  void add_chunk(int t, int p, bool head) {
    std::string ts = std::to_string(t);
    calls.push_back(call("embed_t" + ts, "embed_t" + ts));
    int bucket = 0;
    for (int b : BUCKETS) if (p + t <= b) { bucket = b; break; }
    if (!bucket) throw std::runtime_error("position beyond the compiled limit");
    for (int l = 0; l < NLAYER; l++) {
      if (!layer[l].full) calls.push_back(call("lin_t" + ts, "lin_t" + ts + "|" + std::to_string(l)));
      else {
        std::string k = "full_t" + ts + "_l" + std::to_string(bucket);
        calls.push_back(call(k, k + "|" + std::to_string(l)));
      }
    }
    if (head) calls.push_back(call("head_t" + ts, "head_t" + ts));
    else calls.push_back(call("adv_t" + ts, "adv_t" + ts));
  }

  std::vector<NRT_STATUS> rets;
  clk::time_point t_run;
  void run_calls() {
    if (calls.empty()) return;
    t_run = clk::now();
    rets.assign(calls.size(), NRT_SUCCESS);
    nrta_seq_t seq = 0;
    for (size_t i = 0; i < calls.size(); i++) {
      NRT_STATUS s;
      while ((s = nrta_execute_schedule(calls[i].m, calls[i].in, calls[i].out, 0, &rets[i], &seq)) == NRT_QUEUE_FULL) {}
      CK(s);
    }
    auto ts = clk::now();
    bool done = false;
    while (!done) CK(nrta_is_completed(seq, &done));
    if (g_verbose) logf("  %zu executions: scheduled in %.3f ms, done %.3f ms later", calls.size(), ms_since(t_run) , ms_since(ts));
    calls.clear();
    for (auto r : rets) CK(r);
  }

  void set_pos(int p) {
    int32_t pi[2] = {p, p};
    CK(nrt_tensor_write(pos, pi, 0, sizeof pi));
    std::vector<float> pf(2 * P, (float)p);
    CK(nrt_tensor_write(posf, pf.data(), 0, pf.size() * 4));
  }

  // protocol state: `consumed` tokens are in the state; toks[consumed] holds the last emitted token
  int consumed = 0;
  bool have_state = false;

  // the DeltaNet states are zeroed on the device by the first queued execution of a reset request
  void reset_state() {
    calls.push_back(call("zero_states", "zero_states"));
    consumed = 0; have_state = false;
  }

  std::vector<int> generate(const std::vector<int>& prompt, int max_tokens, bool reset) {
    calls.clear();
    if (max_tokens < 1) throw std::runtime_error("max_tokens must be at least 1");
    int first;  // position whose token is the first output
    if (reset) {
      if (prompt.empty()) throw std::runtime_error("a reset request needs a prompt");
      for (int x : prompt) if (x < 0 || x >= VOCAB) throw std::runtime_error("token id out of range");
      if ((int)prompt.size() + max_tokens > MAXPOS) throw std::runtime_error("prompt plus output exceeds the compiled limit of 8192 positions");
      // the position-0 variants of the first chunk (pchunk512_l512t, pchunk256_l256t) start from zero DeltaNet
      // states on the chip; otherwise the states are zeroed by a separate execution first
      if (prompt.size() < 256) reset_state();
      else { consumed = 0; have_state = false; }
      auto tw = clk::now();
      std::vector<int32_t> pt(prompt.begin(), prompt.end());
      CK(nrt_tensor_write(toks, pt.data(), 0, pt.size() * 4));
      set_pos(0);
      if (g_verbose) logf("  host writes %.3f ms", ms_since(tw));
      int n = (int)prompt.size(), p = 0;
      int last = 0;
      int lastp = 0;
      while (n - p >= 512) { add_pchunk(512, p); lastp = p; p += 512; last = 512; }
      if (n - p >= 256) { add_pchunk(256, p); lastp = p; p += 256; last = 256; }
      if (n - p >= 128) { add_pchunk(128, p); lastp = p; p += 128; last = 128; }
      if (p == n && last) {
        std::string kh = pchunk_name(last, lastp) + "h";
        if (sets.count(kh)) { calls.back() = call(kh, kh); }   // the last chunk with the LM head fused in
        else { std::string h = "headna_t" + std::to_string(last); calls.push_back(call(h, h)); }
      }
      while (p < n) { add_chunk(1, p, p + 1 == n); p += 1; }
      consumed = n; have_state = true;
      first = n;
      for (int i = 1; i < max_tokens; i++) { add_step(consumed); consumed += 1; }
    } else {
      if (!prompt.empty() || !have_state) throw std::runtime_error("a continuation has an empty prompt and follows a generate request");
      if (consumed + max_tokens > MAXPOS) throw std::runtime_error("continuation exceeds the compiled limit of 8192 positions");
      first = consumed + 1;
      for (int i = 0; i < max_tokens; i++) { add_step(consumed); consumed += 1; }
    }
    run_calls();
    std::vector<int32_t> o(max_tokens);
    CK(nrt_tensor_read(toks, o.data(), (size_t)first * 4, (size_t)max_tokens * 4));
    return std::vector<int>(o.begin(), o.end());
  }
};

