// safetensors
struct TensorRef { std::string dtype; std::vector<int64_t> shape; const uint8_t* data; size_t bytes; };

struct SafeTensors {
  std::map<std::string, TensorRef> t;
  std::vector<std::pair<void*, size_t>> maps;
  void open_dir(const std::string& dir) {
    DIR* d = opendir(dir.c_str());
    if (!d) throw std::runtime_error("cannot open model dir " + dir);
    std::vector<std::string> files;
    while (dirent* e = readdir(d)) {
      std::string n = e->d_name;
      if (n.size() > 12 && n.substr(n.size() - 12) == ".safetensors") files.push_back(dir + "/" + n);
    }
    closedir(d);
    if (files.empty()) throw std::runtime_error("no safetensors in " + dir);
    for (auto& f : files) open_file(f);
  }
  void open_file(const std::string& path) {
    int fd = ::open(path.c_str(), O_RDONLY);
    if (fd < 0) throw std::runtime_error("cannot open " + path);
    struct stat st; fstat(fd, &st);
    void* m = mmap(nullptr, st.st_size, PROT_READ, MAP_PRIVATE, fd, 0);
    ::close(fd);
    if (m == MAP_FAILED) throw std::runtime_error("mmap failed " + path);
    maps.push_back({m, (size_t)st.st_size});
    const uint8_t* b = (const uint8_t*)m;
    uint64_t n; memcpy(&n, b, 8);
    std::string hdr((const char*)b + 8, n);
    json::Value h = json::parse(hdr);
    const uint8_t* base = b + 8 + n;
    for (auto& kv : h.obj) {
      if (kv.first == "__metadata__") continue;
      TensorRef r;
      r.dtype = kv.second["dtype"].str;
      for (auto& s : kv.second["shape"].arr) r.shape.push_back((int64_t)s.num);
      size_t a = (size_t)kv.second["data_offsets"].arr[0].num, z = (size_t)kv.second["data_offsets"].arr[1].num;
      r.data = base + a; r.bytes = z - a;
      t[kv.first] = r;
    }
  }
  const TensorRef& get(const std::string& name, const char* dtype, std::vector<int64_t> shape) {
    auto it = t.find(name);
    if (it == t.end()) throw std::runtime_error("missing tensor " + name);
    if (it->second.dtype != dtype) throw std::runtime_error("dtype mismatch for " + name + ": " + it->second.dtype);
    if (it->second.shape != shape) throw std::runtime_error("shape mismatch for " + name);
    return it->second;
  }
};

